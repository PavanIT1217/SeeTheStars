// Builds js/data/place-photos.js: a photo (with credit and licence) for every built-in place, from the lead image of
// its Wikipedia article, hot-linked from Wikimedia Commons like the other photos in the app.
// Usage: node scripts/build-place-photos.mjs   (needs internet; re-run after adding places)
import { writeFileSync } from 'node:fs';
import { PLACES, PLACE_WIKI } from '../js/data/places.js';

const UA = { 'User-Agent': 'SeeTheStars/1.0 (https://seethestars.webappslab.com; pavan@webappslab.com)' };
const get = async (url) => {
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url, { headers: UA });
    if (res.ok) return res.json();
    if (res.status === 404) return null;
    await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
  }
  throw new Error(`Failed: ${url}`);
};
const text = (html) => String(html || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

const out = {};
const missing = [];
for (const [name] of PLACES) {
  const title = PLACE_WIKI[name] || name;
  // pilicense=free: only freely licensed images (skips logos and other non-free files stored on Wikipedia itself).
  const q = await get(`https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1&prop=pageimages%7Cpageprops&piprop=name&pilicense=free&titles=${encodeURIComponent(title)}`);
  const page = q && Object.values(q.query?.pages || {})[0];
  const file = page?.pageimage;
  if (!page || page.missing !== undefined || page.pageprops?.disambiguation !== undefined || !file) { missing.push(`${name} (${page?.pageprops?.disambiguation !== undefined ? 'disambiguation' : 'no free lead image'})`); continue; }
  const info = await get(`https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url%7Cextmetadata&iiurlwidth=320&titles=File:${encodeURIComponent(file)}`);
  const ii = info && Object.values(info.query?.pages || {})[0]?.imageinfo?.[0];
  if (!ii) { missing.push(`${name} (image not on Commons)`); continue; }
  const m = ii.extmetadata || {};
  const license = text(m.LicenseShortName?.value);
  if (!/public domain|^cc|pd|gfdl|^fal|godl/i.test(license)) { missing.push(`${name} (licence: ${license})`); continue; }
  out[name] = { src: (ii.thumburl || ii.url).split('?')[0], credit: text(m.Artist?.value).slice(0, 80) || 'Wikimedia Commons', license, page: ii.descriptionurl };
  await new Promise((r) => setTimeout(r, 120)); // be gentle with the API
}

writeFileSync('js/data/place-photos.js', `// Generated by scripts/build-place-photos.mjs – do not edit by hand.
// A photo for each built-in place: the lead image of its Wikipedia article, from Wikimedia Commons (credit and licence included).
// Offline, or for places without a photo, the Sky Finder draws the place's icon instead.
export const PLACE_PHOTOS = ${JSON.stringify(out, null, 0).replace(/\},"/g, '},\n  "').replace(/^\{"/, '{\n  "').replace(/\}\}$/, '},\n}')};
`);
console.log(`${Object.keys(out).length} photos; no photo for: ${missing.join('; ') || 'none'}`);
