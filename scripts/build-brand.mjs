// Wide graphics: Orion over the curve of the Earth, the icon and the name.
function banner(w, h, { title, line, chips }) {
  // Orion on the right, with the lock-on brackets around Betelgeuse (at -7.1, -1 in Orion's frame).
  const sc = h / 58, ox = w - h * 0.3, oy = h * 0.42;
  const bx = ox - 7.1 * sc, by = oy - 1 * sc, bs = h * 0.1, bq = h * 0.034;
  const sky = `<svg width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" style="position:absolute;inset:0">
    <defs><radialGradient id="g" cx="70%" cy="20%" r="90%"><stop offset="0" stop-color="#26267a"/><stop offset=".5" stop-color="#11113f"/><stop offset="1" stop-color="#04050d"/></radialGradient>
    <linearGradient id="e" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#0f2a4a"/><stop offset="1" stop-color="#03070f"/></linearGradient>
    <filter id="b"><feGaussianBlur stdDeviation="${h / 28}"/></filter></defs>
    <rect width="${w}" height="${h}" fill="url(#g)"/>
    <path d="M${w * 0.3} ${h} C ${w * 0.5} ${h * 0.5}, ${w * 0.7} ${h * 0.2}, ${w} ${-h * 0.1} L ${w} ${h * 0.25} C ${w * 0.75} ${h * 0.45}, ${w * 0.55} ${h * 0.8}, ${w * 0.45} ${h * 1.1} Z" fill="#9a7bff" opacity=".18" filter="url(#b)"/>
    <g transform="translate(${ox} ${oy})">${constellationSvg('Ori', sc)}</g>
    <g transform="translate(${bx - bs / 2} ${by - bs / 2})" fill="none" stroke="#ffd36b" stroke-width="${h / 110}" stroke-linecap="round">
      <path d="M0 ${bq} V0 H${bq}"/><path d="M${bs - bq} 0 H${bs} V${bq}"/><path d="M${bs} ${bs - bq} V${bs} H${bs - bq}"/><path d="M${bq} ${bs} H0 V${bs - bq}"/></g>
    <ellipse cx="${w * 0.5}" cy="${h * 2.05}" rx="${w * 1.1}" ry="${h * 1.25}" fill="none" stroke="#5ad7ff" stroke-width="${h / 40}" opacity=".5" filter="url(#b)"/>
    <ellipse cx="${w * 0.5}" cy="${h * 2.05}" rx="${w * 1.1}" ry="${h * 1.25}" fill="url(#e)" stroke="#8fe9ff" stroke-width="${h / 220}"/>
  </svg>`;
  const u = h / 500;
  return `<div style="position:relative;width:${w}px;height:${h}px;overflow:hidden">${sky}
    <div style="position:absolute;left:${56 * u}px;top:0;bottom:${40 * u}px;display:flex;align-items:center;gap:${30 * u}px">
      <div style="border-radius:${44 * u}px;overflow:hidden;box-shadow:0 ${12 * u}px ${40 * u}px rgba(0,0,0,.5);flex:none">${svgImg(icon, 190 * u)}</div>
      <div style="color:#fff">
        <div style="font:700 ${62 * u}px/1 'Space Grotesk';letter-spacing:-.01em">${title}</div>
        <div style="font:500 ${29 * u}px/1.3 'Space Grotesk';color:#cfd6ff;margin-top:${14 * u}px;max-width:${w * 0.42}px">${line}</div>
        <div style="display:flex;gap:${8 * u}px;margin-top:${20 * u}px;flex-wrap:wrap;max-width:${560 * u}px">${chips.map((c) => `<span style="font:600 ${17 * u}px 'Space Grotesk';color:#ffd36b;border:${1.5 * u}px solid rgba(255,211,107,.55);border-radius:99px;padding:${5 * u}px ${12 * u}px">${c}</span>`).join('')}</div>
      </div></div></div>`;
}
