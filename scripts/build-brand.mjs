// A constellation drawn the way the Sky Finder draws it: picture, stick figure and stars, as SVG in its flat frame.
function constellationSvg(id, scale) {
  const D = Math.PI / 180, art = FIGURE_ART[id], [ra0, dec0] = art.c;
  const toFrame = (ra, dec) => {
    const dr = (ra - ra0) * D, d = dec * D, d0 = dec0 * D;
    const cc = Math.sin(d0) * Math.sin(d) + Math.cos(d0) * Math.cos(d) * Math.cos(dr);
    return [-(Math.cos(d) * Math.sin(dr) / cc) / D, -((Math.cos(d0) * Math.sin(d) - Math.sin(d0) * Math.cos(d) * Math.cos(dr)) / cc) / D, cc];
  };
  const c = CONSTELLATIONS.find((x) => x.id === id);
  let out = `<g transform="scale(${scale})">`;
  out += art.parts.map(([w, d]) => (w
    ? `<path d="${d}" fill="none" stroke="#f5e3b5" stroke-opacity="0.2" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`
    : `<path d="${d}" fill="#f5e3b5" fill-opacity="0.2" stroke="#f5e3b5" stroke-opacity="0.45" stroke-width="${0.9 / scale}"/>`)).join('');
  for (const l of c.lines) {
    const pts = [];
    for (let k = 0; k < l.length; k += 2) pts.push(toFrame(l[k], l[k + 1]).slice(0, 2).map((v) => v.toFixed(2)).join(','));
    out += `<polyline points="${pts.join(' ')}" fill="none" stroke="#7fdcff" stroke-opacity="0.6" stroke-width="${1.6 / scale}"/>`;
  }
  for (let i = 0; i < STARS.length / 4; i++) {
    const [ra, dec, mag] = [STARS[i * 4], STARS[i * 4 + 1], STARS[i * 4 + 2]];
    if (mag > 5.2) break;
    const [x, y, cc] = toFrame(ra, dec);
    if (cc < 0.5 || Math.abs(x) > 40 || Math.abs(y) > 30) continue;
    out += `<circle cx="${x.toFixed(2)}" cy="${y.toFixed(2)}" r="${(Math.max(0.6, 3.6 - mag * 0.6) / scale).toFixed(3)}" fill="#fff" fill-opacity="${Math.min(1, 1.15 - mag * 0.13).toFixed(2)}"/>`;
  }
  return `${out}</g>`;
}

function shoot(name, html, w, h, { transparent = false } = {}) {
  const page = join(tmp, `${name.replace(/\W/g, '_')}.html`);
  writeFileSync(page, `<!doctype html><html><head><meta charset="utf-8"><style>${FONTS} html,body{margin:0;width:${w}px;height:${h}px;overflow:hidden;background:${transparent ? 'transparent' : '#05060f'}}</style></head><body>${html}</body></html>`);
  const args = ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--allow-file-access-from-files', '--force-device-scale-factor=1',
    `--window-size=${w},${h}`, `--screenshot=${join(root, name)}`, '--virtual-time-budget=3000'];
  if (transparent) args.push('--default-background-color=00000000');
  execFileSync(CHROME, [...args, `file://${page}`], { stdio: 'ignore' });
  console.log(`${name} (${w}×${h})`);
}

