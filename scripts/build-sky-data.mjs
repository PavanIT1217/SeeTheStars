// Builds js/data/sky.js (stars and the 88 constellations) from the d3-celestial data files.
// Usage: node scripts/build-sky-data.mjs <folder with stars.6.json, starnames.json, constellations*.json>
// Source: https://github.com/ofrohn/d3-celestial/tree/master/data (© Olaf Frohn, BSD-3-Clause).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = process.argv[2];
if (!src) throw new Error('Pass the folder that holds the d3-celestial data files');
const read = (f) => JSON.parse(readFileSync(join(src, f), 'utf8'));
const ra = (lon) => +((lon + 360) % 360).toFixed(2); // d3-celestial stores RA as -180..180
const r2 = (x) => +x.toFixed(2);

const names = read('starnames.json');
const stars = read('stars.6.json').features
  .map((f) => ({ hip: f.id, ra: ra(f.geometry.coordinates[0]), dec: r2(f.geometry.coordinates[1]), mag: r2(f.properties.mag), bv: r2(parseFloat(f.properties.bv) || 0.6) }))
  .sort((a, b) => a.mag - b.mag);

const STARS = stars.flatMap((s) => [s.ra, s.dec, s.mag, s.bv]);
const STAR_NAMES = stars.flatMap((s, i) => {
  const n = names[s.hip];
  if (!n) return [];
  const label = n.name || (n.desig && /^\p{Script=Greek}/u.test(n.desig) ? `${n.desig} ${n.c}` : '');
  return label ? [[i, label, n.c]] : [];
});

const lines = Object.fromEntries(read('constellations.lines.json').features.map((f) => [f.id, f.geometry.coordinates]));
const bounds = Object.fromEntries(read('constellations.bounds.json').features.map((f) => [f.id, f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.coordinates.flat()]));
const CONSTELLATIONS = read('constellations.json').features.map((f) => {
  const p = f.properties;
  return {
    id: f.id,
    name: p.name,
    gen: p.gen,
    hi: p.hi,
    es: p.es,
    rank: +p.rank,
    label: [ra(f.geometry.coordinates[0]), r2(f.geometry.coordinates[1])],
    lines: (lines[f.id] || []).map((l) => l.flatMap(([x, y]) => [ra(x), r2(y)])),
    bounds: (bounds[f.id] || []).map((ring) => ring.flatMap(([x, y]) => [ra(x), r2(y)])),
  };
});

const out = `// Generated by scripts/build-sky-data.mjs – do not edit by hand.
// Stars brighter than magnitude 6 and the 88 IAU constellations (Serpens comes in two parts),
// from d3-celestial © Olaf Frohn, BSD-3-Clause (https://github.com/ofrohn/d3-celestial).

// [ra, dec, magnitude, B–V colour index] per star, brightest first. Degrees, J2000.
export const STARS = ${JSON.stringify(STARS)};

// [index into STARS, name, constellation]
export const STAR_NAMES = ${JSON.stringify(STAR_NAMES)};

// lines: polylines as flat [ra, dec, ra, dec, …]; bounds: boundary rings in the same form; label: where to write the name.
export const CONSTELLATIONS = ${JSON.stringify(CONSTELLATIONS)};
`;
writeFileSync('js/data/sky.js', out);
console.log(`${stars.length} stars (${STAR_NAMES.length} named), ${CONSTELLATIONS.length} constellations, ${(out.length / 1024).toFixed(0)} KB`);
