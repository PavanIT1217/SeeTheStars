// Builds js/data/sky.js (stars and the 88 constellations) from the d3-celestial data files.
// Usage: node scripts/build-sky-data.mjs <folder with stars.6.json, starnames.json, constellations*.json, messier.json> <hygdata_v41.csv>
// Sources: https://github.com/ofrohn/d3-celestial/tree/master/data (© Olaf Frohn, BSD-3-Clause), and star distances from
// the HYG database v4.1 (https://github.com/astronexus/HYG-Database, © David Nash, CC BY-SA 4.0), matched by Hipparcos number.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [src, hygFile] = process.argv.slice(2);
if (!src || !hygFile) throw new Error('Pass the folder that holds the d3-celestial data files, then the HYG csv');
const read = (f) => JSON.parse(readFileSync(join(src, f), 'utf8'));
const ra = (lon) => +((lon + 360) % 360).toFixed(2); // d3-celestial stores RA as -180..180
const r2 = (x) => +x.toFixed(2);

const names = read('starnames.json');

// Hipparcos number -> distance in light-years (HYG stores parsecs; 100000 means unknown).
const hyg = readFileSync(hygFile, 'utf8').split('\n');
const col = Object.fromEntries(hyg[0].split(',').map((h, i) => [h.replace(/"/g, ''), i]));
const lyByHip = new Map();
for (const row of hyg.slice(1)) {
  const c = row.split(',');
  const hip = +c[col.hip], pc = +c[col.dist];
  if (hip && pc > 0 && pc < 100000) lyByHip.set(hip, pc * 3.26156);
}
// Two significant figures beyond 100 ly: the measurements aren't better than that.
const roundLy = (ly) => (ly < 10 ? +ly.toFixed(1) : ly < 100 ? Math.round(ly) : +ly.toPrecision(2));
const stars = read('stars.6.json').features
  .map((f) => ({ hip: f.id, ra: ra(f.geometry.coordinates[0]), dec: r2(f.geometry.coordinates[1]), mag: r2(f.properties.mag), bv: r2(parseFloat(f.properties.bv) || 0.6) }))
  .sort((a, b) => a.mag - b.mag);

const STARS = stars.flatMap((s) => [s.ra, s.dec, s.mag, s.bv]);
const STAR_NAMES = stars.flatMap((s, i) => {
  const n = names[s.hip];
  if (!n) return [];
  const label = n.name || (n.desig && /^\p{Script=Greek}/u.test(n.desig) ? `${n.desig} ${n.c}` : '');
  const ly = lyByHip.get(s.hip);
  return label ? [ly ? [i, label, n.c, roundLy(ly)] : [i, label, n.c]] : [];
});

const lines = Object.fromEntries(read('constellations.lines.json').features.map((f) => [f.id, f.geometry.coordinates]));
const bounds = Object.fromEntries(read('constellations.bounds.json').features.map((f) => [f.id, f.geometry.type === 'Polygon' ? f.geometry.coordinates : f.geometry.coordinates.flat()]));
const CONSTELLATIONS = read('constellations.json').features.map((f) => {
  const p = f.properties;
  return {
    id: f.id,
    name: p.name,
    gen: p.gen,
    hi: p.hi,
    es: p.es,
    rank: +p.rank,
    label: [ra(f.geometry.coordinates[0]), r2(f.geometry.coordinates[1])],
    lines: (lines[f.id] || []).map((l) => l.flatMap(([x, y]) => [ra(x), r2(y)])),
    bounds: (bounds[f.id] || []).map((ring) => ring.flatMap(([x, y]) => [ra(x), r2(y)])),
  };
});

// [M number, NGC designation, common name, type, magnitude, ra, dec]
const MESSIER = read('messier.json').features.map((f) => {
  const p = f.properties;
  return [+f.id.slice(1), p.desig || '', p.alt || '', p.type, p.mag, ra(f.geometry.coordinates[0]), r2(f.geometry.coordinates[1])];
});

const out = `// Generated by scripts/build-sky-data.mjs – do not edit by hand.
// Stars brighter than magnitude 6 and the 88 IAU constellations (Serpens comes in two parts),
// from d3-celestial © Olaf Frohn, BSD-3-Clause (https://github.com/ofrohn/d3-celestial).

// [ra, dec, magnitude, B–V colour index] per star, brightest first. Degrees, J2000.
export const STARS = ${JSON.stringify(STARS)};

// [index into STARS, name, constellation, distance in light-years (when known)]. Distances: HYG database v4.1,
// © David Nash, CC BY-SA 4.0 (https://github.com/astronexus/HYG-Database).
export const STAR_NAMES = ${JSON.stringify(STAR_NAMES)};

// lines: polylines as flat [ra, dec, ra, dec, …]; bounds: boundary rings in the same form; label: where to write the name.
export const CONSTELLATIONS = ${JSON.stringify(CONSTELLATIONS)};

// The 110 Messier objects: [M number, NGC, common name, type, magnitude, ra, dec].
// Types: gc globular cluster, oc open cluster, pn planetary nebula, en/rn/sfr nebula, snr supernova remnant,
// sp/el/ir/s0 galaxy, ds double star, as asterism.
export const MESSIER = ${JSON.stringify(MESSIER)};
`;
writeFileSync('js/data/sky.js', out);
console.log(`${stars.length} stars (${STAR_NAMES.length} named, ${STAR_NAMES.filter((n) => n[3]).length} with distances), ${CONSTELLATIONS.length} constellations, ${MESSIER.length} Messier objects, ${(out.length / 1024).toFixed(0)} KB`);
