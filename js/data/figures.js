// Pictures for the famous constellations: the hunter, the bear, the lion… drawn over the real stars.
// Each figure is drawn in a flat frame centred on `c` ([ra, dec], degrees): x is degrees to the right (west)
// and y degrees down (south) as you face the constellation, so the paths read like ordinary SVG.
// Parts are [width, path]: width 0 is a filled shape, any other width is a stroke that many degrees thick.
// Paths use absolute M, L, Q, C and Z only. Artwork made for See the Stars.

const circle = (x, y, r) => {
  const k = r * 0.5523;
  return `M ${x - r} ${y} C ${x - r} ${y - k} ${x - k} ${y - r} ${x} ${y - r} C ${x + k} ${y - r} ${x + r} ${y - k} ${x + r} ${y} C ${x + r} ${y + k} ${x + k} ${y + r} ${x} ${y + r} C ${x - k} ${y + r} ${x - r} ${y + k} ${x - r} ${y} Z`;
};

