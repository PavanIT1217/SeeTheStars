// SVG path (absolute M L Q C Z) -> polylines of [x, y] points, curves sampled into short straight pieces.
export function pathToPolylines(d, steps = 8) {
  const tok = d.match(/[MLQCZ]|-?\d*\.?\d+(?:e-?\d+)?/gi) || [];
  const lines = [];
  let cur = null, x = 0, y = 0, sx = 0, sy = 0, i = 0;
  const num = () => +tok[i++];
  while (i < tok.length) {
    const cmd = tok[i++].toUpperCase();
    if (cmd === 'M') { x = num(); y = num(); sx = x; sy = y; cur = [[x, y]]; lines.push(cur); }
    else if (cmd === 'L') { x = num(); y = num(); cur.push([x, y]); }
    else if (cmd === 'Q') {
      const [x1, y1, x2, y2] = [num(), num(), num(), num()];
      for (let s = 1; s <= steps; s++) { const t = s / steps, u = 1 - t; cur.push([u * u * x + 2 * u * t * x1 + t * t * x2, u * u * y + 2 * u * t * y1 + t * t * y2]); }
      x = x2; y = y2;
    } else if (cmd === 'C') {
      const [x1, y1, x2, y2, x3, y3] = [num(), num(), num(), num(), num(), num()];
      for (let s = 1; s <= steps; s++) { const t = s / steps, u = 1 - t; cur.push([u ** 3 * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3, u ** 3 * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3]); }
      x = x3; y = y3;
    } else if (cmd === 'Z') { cur.push([sx, sy]); x = sx; y = sy; }
    else throw new Error(`Unsupported path command ${cmd}`);
  }
  return lines;
}

// Flat-frame point -> [ra, dec] (inverse gnomonic projection around the centre).
export function frameToSky([x, y], [ra0, dec0]) {
  const D = Math.PI / 180;
  const xi = -x * D, eta = -y * D, d0 = dec0 * D;
  const rho = Math.hypot(xi, eta), c = Math.atan(rho);
  if (!rho) return [ra0, dec0];
  const dec = Math.asin(Math.cos(c) * Math.sin(d0) + (eta * Math.sin(c) * Math.cos(d0)) / rho);
  const ra = ra0 * D + Math.atan2(xi * Math.sin(c), rho * Math.cos(d0) * Math.cos(c) - eta * Math.sin(d0) * Math.sin(c));
  return [(((ra / D) % 360) + 360) % 360, dec / D];
}
